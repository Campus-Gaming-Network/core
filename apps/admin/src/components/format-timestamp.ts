/** Formats an API timestamp in a time zone, naming the zone it is shown in. */
export function formatTimestamp(value: string, timeZone: string): string {
  return new Intl.DateTimeFormat("en", {
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "numeric",
    minute: "2-digit",
    timeZone,
    timeZoneName: "short",
  }).format(new Date(value));
}
